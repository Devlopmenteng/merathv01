type ChartDataItem = {
  label: string;
  value: number;
  color: string;
};

const AnimatedNumber = ({ value, style }: { value: number; style?: any }) => {
  const animatedValue = useRef(new Animated.Value(0)).current;

  useEffect(() => {
    Animated.timing(animatedValue, {
      toValue: value,
      duration: 1000,
      useNativeDriver: false,
    }).start();
  }, [value]);

  const display = animatedValue.interpolate({
    inputRange: [0, value],
    outputRange: [0, value],
    extrapolate: 'clamp',
  });

  return <Animated.Text style={style}>{display}</Animated.Text>;
};

export const Results = ({ navigation }: { navigation: any }) => {
  const { isPremium } = usePremium();
  const { state } = useCalc();
  const theme = useAppTheme();
  const [result, setResult] = useState<CalculationResult | null>(null);
  const [loading, setLoading] = useState(true);
  const [showPercentage, setShowPercentage] = useState(false);

  const chartData = useMemo<ChartDataItem[]>(() => {
    if (!result) return [];
    return result.shares.map((s) => ({
      label: s.name,
      value: s.amount,
      color: '#1B6B4A',
    }));
  }, [result]);

  useEffect(() => {
    setLoading(true);

    const estate: EstateInput = {
      total: state.total,
      funeral: state.funeral,
      debts: state.debts,
      will: state.will,
    };

    const res = calculateInheritance(state.madhab, estate, heirsArrayToObject(state.heirs));
    let confidence = 100;

    if ((res.netEstate ?? 0) <= 0) confidence -= 50;
    if (heirsArrayToObject(state.heirs).length === 0) confidence -= 30;

    const safeResult: CalculationResult = {
      ...res,
      confidence: Math.max(confidence, 10),
    };

    setResult(safeResult);
    setLoading(false);

    incrementCalculationCount().catch(() => {});
    saveAuditTrail({
      id: Date.now().toString(),
      timestamp: new Date().toISOString(),
      madhab: state.madhab,
      netTotal: safeResult.netEstate ?? 0,
      shares: safeResult.shares,
      steps: safeResult.steps.map(({ title, description }) => ({ title, description })),
    }).catch(() => {});
  }, [state.madhab, state.total, state.funeral, state.debts, state.will, heirsArrayToObject(state.heirs)]);

  const generatePDF = async () => {
    if (!result) return;
    if (isPremium) {
      await generateLegalReport(result, state.madhab);
      return;
    }

    const html = `
      <html><head><style>body{font-family:Arial;padding:20px}h1{color:#1B6B4A}</style></head>
      <body>
        <h1>Inheritance Report</h1>
        <p>Madhab: ${result.madhab}</p>
        <p>Net Estate: $${result.netEstate}</p>
        <h2>Distribution</h2>
        <ul>${result.shares
          .map(
            (s) =>
              `<li>${s.name}: $${s.amount.toFixed(2)} (${s.fraction?.numerator}/${s.fraction?.denominator})</li>`,
          )
          .join('')}</ul>
        <footer>Generated by Merath App - ${new Date().toLocaleDateString()}</footer>
      </body></html>
    `;
    const { uri } = await Print.printToFileAsync({ html });
    if (Platform.OS === 'web') window.open(uri);
    else await Sharing.shareAsync(uri);
  };

  const copyAsText = async () => {
    if (!result) return;
    let text = `Net Estate: $${result.netEstate}\n\n`;
    result.shares.forEach((s) => {
      text += `${s.name}: $${s.amount.toFixed(2)} (${s.fraction?.numerator}/${s.fraction?.denominator})\n`;
    });
    await Clipboard.setStringAsync(text);
    Alert.alert('Copied', 'Results copied to clipboard');
  };

  const confidenceColor =
    result?.confidence ?? 0 >= 70
      ? theme.colors.success
      : result?.confidence ?? 0 >= 40
      ? theme.colors.warning
      : theme.colors.error;

  if (loading || !result) return <ResultsSkeleton />;

  const renderSpecialCases = () => {
    if (!result) return null;
    const cases = [];
    if (result.awlApplied) cases.push({ name: "العول", desc: "تم تطبيق العول لزيادة أصل المسألة" });
    if (result.raddApplied) cases.push({ name: "الرد", desc: "تم تطبيق الرد لتوزيع الباقي على أصحاب الفروض" });
    if (result.bloodRelativesApplied) cases.push({ name: "ذوو الأرحام", desc: "تم توزيع الباقي على ذوي الأرحام" });
    if (cases.length === 0) return null;
    return (
      <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 8, marginVertical: 12 }}>
        {cases.map((c, i) => (
          <View key={i} style={{ backgroundColor: theme.colors.primaryLight, paddingHorizontal: 12, paddingVertical: 6, borderRadius: 20 }}>
            <Text style={{ color: theme.colors.primary, fontSize: 12 }}>{c.name}</Text>
          </View>
        ))}
      </View>
    );
  };
  return (
    <ExportBar resultData={result}>
      <ScrollView contentContainerStyle={{ padding: theme.spacing.lg }}>
        <View
          style={{
            backgroundColor: theme.colors.primary,
            borderRadius: theme.radius.lg,
            padding: theme.spacing.lg,
            alignItems: 'center',
            marginBottom: theme.spacing.lg,
          }}
        >
          <Text style={{ color: theme.colors.onPrimary, fontSize: 24 }}>{t('netEstate')}</Text>
          <AnimatedNumber value={result.netEstate ?? 0} style={{ color: theme.colors.onPrimary, fontSize: 48 }} />
        </View>

        <View style={{ flexDirection: 'row', alignItems: 'center', marginBottom: theme.spacing.md }}>
          <View
            style={{
              height: 10,
              flex: 1,
              backgroundColor: theme.colors.surfaceVariant,
              borderRadius: 5,
              overflow: 'hidden',
            }}
          >
            <View
              style={{
                height: 10,
                width: `${result.confidence}%`,
                backgroundColor: confidenceColor,
                borderRadius: 5,
              }}
            />
          </View>
          <Text style={{ marginStart: 8, color: confidenceColor, fontWeight: '600' }}>
            {result.confidence}%
          </Text>
        </View>

        <Text style={theme.typography.caption}>{t('confidence')}</Text>

        <View style={{ flexDirection: 'row', justifyContent: 'flex-end', alignItems: 'center', marginVertical: 12 }}>
          <Text style={{ marginEnd: 8 }}>{t('fractions')}</Text>
          <Switch value={showPercentage} onValueChange={setShowPercentage} />
          <Text style={{ marginStart: 8 }}>{t('percentages')}</Text>
        </View>

        <PieChart data={chartData} />

        <Text style={theme.typography.h2}>{t('distribution')}</Text>
        {result.shares.map((share, idx) => {
          const displayAmount = showPercentage
            ? `${((share.amount / (result.netEstate ?? 1)) * 100).toFixed(1)}%`
            : `$${share.amount.toFixed(2)}`;
  const renderSpecialCases = () => {
    if (!result) return null;
    const cases = [];
    if (result.awlApplied) cases.push({ name: "العول", desc: "تم تطبيق العول لزيادة أصل المسألة" });
    if (result.raddApplied) cases.push({ name: "الرد", desc: "تم تطبيق الرد لتوزيع الباقي على أصحاب الفروض" });
    if (result.bloodRelativesApplied) cases.push({ name: "ذوو الأرحام", desc: "تم توزيع الباقي على ذوي الأرحام" });
    if (cases.length === 0) return null;
    return (
      <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 8, marginVertical: 12 }}>
        {cases.map((c, i) => (
          <View key={i} style={{ backgroundColor: theme.colors.primaryLight, paddingHorizontal: 12, paddingVertical: 6, borderRadius: 20 }}>
            <Text style={{ color: theme.colors.primary, fontSize: 12 }}>{c.name}</Text>
          </View>
        ))}
      </View>
    );
  };
          return (
            <View
              key={idx}
              style={{
                flexDirection: 'row',
                justifyContent: 'space-between',
                paddingVertical: theme.spacing.sm,
                borderBottomWidth: 1,
                borderColor: theme.colors.outline,
              }}
            >
              <Text style={theme.typography.body}>
                {share.name} ({share.fraction?.numerator}/{share.fraction?.denominator})
              </Text>
              <Text style={theme.typography.body}>{displayAmount}</Text>
            </View>
          );
        })}

        <Text style={[theme.typography.h2, { marginTop: 20 }]}>{t('steps')}</Text>
        {result.steps.map((step, idx) => (
          <View key={idx} style={{ paddingVertical: 4 }}>
            <Text style={{ fontWeight: '600' }}>{step.title}</Text>
            <Text style={{ fontSize: 12 }}>{step.description}</Text>
          </View>
        ))}

        <View style={{ flexDirection: 'row', justifyContent: 'space-around', marginTop: theme.spacing.lg }}>
          <Button title={t('compare')} onPress={() => navigation.navigate('Comparison')} mode="outlined" />
          <Button title={t('history')} onPress={() => navigation.navigate('History')} mode="outlined" />
        </View>

        <View style={{ flexDirection: 'row', justifyContent: 'space-around', marginTop: theme.spacing.sm }}>
          <Button title={t('settings')} onPress={() => navigation.navigate('Settings')} mode="outlined" />
          <Button title={t('copy')} onPress={copyAsText} mode="outlined" />
        </View>

        <View style={{ flexDirection: 'row', justifyContent: 'space-around', marginTop: theme.spacing.sm }}>
          <Button title={t('pdf')} onPress={generatePDF} mode="outlined" />
          <Button
            title={t('share')}
            onPress={() => {
              const link = `merath://setup?total=${state.total}&madhab=${state.madhab}`;
              Clipboard.setStringAsync(link);
              Alert.alert(t('share'), t('deepLinkCopied'));
            }}
            mode="outlined"
          />
        </View>
      </ScrollView>
    </ExportBar>
  );
};
